#!/usr/bin/env python3
"""Write figures/README.md: the figures with the numbers that go with them.

Every number in the prose is computed here from the catalog tables. None is typed
by hand, so the page cannot drift from the data it describes.

    uv run --extra viz python scripts/popseq_figures.py
    uv run python scripts/popseq_report.py
"""
from __future__ import annotations

import csv
import gzip
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUMMARY = os.path.join(HERE, "catalog", "summary")
KINGDOM = os.path.join(HERE, "catalog", "kingdom")
OUT = os.path.join(HERE, "figures", "README.md")
SNAPSHOT = "2026-11-06"


def read(path):
    with gzip.open(path, "rt", newline="") as fh:
        if not fh.readline().startswith("#"):
            fh.seek(0)
        return list(csv.DictReader(fh))


def fig(name, caption, alt):
    return (
        f'<picture>\n'
        f'  <source media="(prefers-color-scheme: dark)" srcset="{name}.dark.png">\n'
        f'  <img alt="{alt}" src="{name}.light.png">\n'
        f'</picture>\n\n'
        f'{caption} &nbsp;·&nbsp; [PDF]({name}.pdf) &nbsp;·&nbsp; '
        f'[light PNG]({name}.light.png) &nbsp;·&nbsp; [dark PNG]({name}.dark.png)\n'
    )


def main():
    sp = read(os.path.join(KINGDOM, "fungi_species_summary.csv.gz"))
    yr = read(os.path.join(SUMMARY, "by_year.csv.gz"))
    cov = read(os.path.join(SUMMARY, "coverage.csv.gz"))
    clon = read(os.path.join(SUMMARY, "clonality.csv.gz"))
    geo = read(os.path.join(SUMMARY, "geography.csv.gz"))

    iso = sorted((int(r["isolates"]) for r in sp), reverse=True)
    runs = sum(int(r["runs"]) for r in sp)
    tb = sum(float(r["est_download_tb"]) for r in sp)
    n100 = sum(1 for v in iso if v >= 100)
    n10k = sum(1 for v in iso if v >= 10000)
    nlt100 = sum(1 for v in iso if v < 100)
    n1 = sum(1 for v in iso if v == 1)

    recent = sum(int(r["runs"]) for r in yr if int(r["year"]) >= 2024)
    yrs = defaultdict(int)
    for r in yr:
        yrs[int(r["year"])] += int(r["runs"])

    big = [r for r in clon if int(r["isolates"]) >= 100]
    half = [r for r in big
            if int(r["largest_study"]) / int(r["isolates"]) >= 0.5]

    covbig = [r for r in cov if r["median_cov"]]
    ge15 = sum(int(r["runs_ge_15x"]) for r in covbig)
    withest = sum(int(r["runs_with_estimate"]) for r in covbig)

    NOT_A_PLACE = {"missing", "not provided", "not collected", "not applicable",
                   "unknown", "na", "none", "null", "n/a", "uncalculated",
                   "not determined", "restricted access"}
    ctry = defaultdict(int)
    placeholder = 0
    for r in geo:
        c = r["country"].strip()
        if c.lower() in NOT_A_PLACE:
            placeholder += int(r["isolates"])
        else:
            ctry[c] += int(r["isolates"])
    placed = sum(ctry.values())
    top1 = max(ctry.items(), key=lambda kv: kv[1])

    md = f"""# What is in the archive

Figures over the fungal population-sequencing catalog. Generated by
`scripts/popseq_figures.py` and `scripts/popseq_report.py` from the tables in
`catalog/summary/` and `catalog/kingdom/`. Source snapshot: ENA {SNAPSHOT}.

Each figure ships three files: a light PNG, a dark PNG, and a vector PDF for
print and slides. The page below picks the PNG that matches your theme. Every
number on this page is computed from the tables at generation time.

**One caveat that applies to every figure.** These are *public whole-genome
Illumina runs of fungal isolates*, as the two archives describe them. A run count
is not a strain count, an isolate count is not an independent-sample count, and
every count here is a floor: ENA holds runs with an empty `tax_id` that no
taxonomy query reaches (issue #2).

## At a glance

| | |
|---|---|
| Runs | {runs:,} |
| Distinct isolates | {sum(iso):,} |
| Species taxids | {len(iso):,} |
| Species with 100+ isolates | {n100} |
| Species with a single isolate | {n1:,} |
| Estimated size, one run per isolate | {tb:,.0f} TB |

---

## 1. The archive is young and still accelerating

{fig("01_cumulative_runs",
     f"**Left:** every fungal WGS run, cumulated by the year it became public. "
     f"**Right:** the six largest species on a log scale, which is the only way "
     f"they fit on one axis. {recent:,} runs — "
     f"{recent / runs * 100:.0f}% of the archive — became public in 2024 or later.",
     "Cumulative fungal WGS runs by year, whole kingdom and six largest species")}

The kingdom curve has no plateau. Anything built on this catalog needs to be
regenerable rather than a one-time snapshot, because the snapshot is stale within
months.

---

## 2. A few huge species, and a very long tail

{fig("02_isolates_rank",
     f"Isolates per species against species rank, both axes log. "
     f"{n10k} species hold more than 10,000 isolates; {nlt100:,} of {len(iso):,} "
     f"hold fewer than 100, and {n1:,} hold exactly one.",
     "Rank curve of isolates per species on log axes")}

This shape is why the catalog has a depth-tier policy. Downloading everything for
the head of this curve is tens of terabytes for two species, while the tail is
mostly single genomes that are not a population at all. {n100} species have
100 or more isolates, and those are the ones worth a population analysis.

---

## 3. Depth is usually sufficient, and sometimes is not

{fig("03_coverage",
     f"Estimated depth for the 25 species with the most runs. Bar is p10 to p90, "
     f"dot is the median. Depth is `base_count` over the NCBI reference assembly "
     f"size, so it is an estimate, not a measurement on the reads. "
     f"{ge15:,} of {withest:,} runs ({ge15 / withest * 100:.0f}%) clear 15x.",
     "Depth per species, p10 to p90 with the median")}

Most species sit well above 15x at the median, but the p10 end crosses the line
for several. Depth has to be filtered per run, not assumed per species. The
species with an estimate at all are limited by whether a reference assembly size
could be resolved: {len(covbig)} of {len(iso):,} species.

---

## 4. A run count is not a strain count

{fig("04_clonality",
     f"For each species with 100 or more isolates, the share of its isolates that "
     f"come from its single largest study. {len(half)} of {len(big)} species take "
     f"half or more of their isolates from one study.",
     "Share of each species coming from its largest single study")}

A species whose isolates come from one outbreak study is one clonal cluster
sampled many times, not a diverse population. For a question about standing
variation this is the difference between a usable panel and a misleading one. The
catalog records studies per species so this can be filtered before download, not
discovered afterwards.

---

## 5. Where the isolates come from

{fig("05_geography",
     f"Top 25 countries by isolates with a recorded country. {placed:,} isolates "
     f"across {len(ctry):,} countries carry a country name; a further "
     f"{placeholder:,} carry a placeholder string and are not drawn. "
     f"{top1[0]} alone accounts for {top1[1] / placed * 100:.0f}%.",
     "Isolates by country of origin, top 25")}

Sampling is heavily concentrated. Roughly
{sum(1 for v in ctry.values() if v < 100):,} of the {len(ctry):,} countries
present contribute fewer than 100 isolates each. Any statement about global
diversity from this archive is a statement about where people sequence.

A choropleth map was not produced. The plotting environment has no geographic
library, and adding one pulls in a heavy dependency chain plus a world-boundary
file that would have to be downloaded and vendored. The bar chart carries the same
information without that cost. Say the word and the map gets built.

---

## Regenerating this page

```bash
uv run --extra viz python scripts/popseq_figures.py   # 15 files into figures/
uv run python scripts/popseq_report.py                # this page
```

Both read only committed catalog tables. Neither touches the network.

Colours are the validated default categorical palette, checked against the
colourblind-separation and contrast gates for both the light and the dark surface
on {SNAPSHOT}. Light and dark are two renders with the palette stepped for each
surface, not an inversion. Where a series colour falls below 3:1 on the light
surface, the series also carries a direct text label, so identity never rests on
colour alone.
"""
    with open(OUT, "w") as fh:
        fh.write(md)
    print(f"wrote {OUT} ({len(md.splitlines())} lines)")


if __name__ == "__main__":
    main()
