#!/usr/bin/env python3
"""Build the dataset summary tables from the kingdom catalog (issue #9).

Reads only files already on disk. No network.

Inputs
    catalog/kingdom/fungi_species_summary.csv.gz   taxid-keyed species table (#1)
    catalog/taxonomy_species_map.csv.gz            taxid -> species taxid
    cache/fungi_runs_ena_<date>.tsv.gz             the run table
    catalog/kingdom/fungi_biosamples.csv.gz        BioSample attributes

Outputs, all under catalog/summary/, each with a provenance header line:
    by_year.csv.gz              runs and isolates per species per release year
    clonality.csv.gz            isolates per study, a proxy for independence
    geography.csv.gz            country counts per species
    coverage.csv.gz             estimated depth distribution per species
    host_source.csv.gz          host and isolation_source where populated

Two things these tables deliberately do NOT claim:

  Counts are floors. An ENA tax_tree query cannot see a run ENA holds with no taxid
  assigned, so every count here understates by an unknown amount (issue #2).

  Runs are not independent strains. Candidozyma auris has about 28,000 runs that are
  largely clonal outbreak surveillance. The clonality table exists to make that
  visible rather than to let a run count stand in for a strain count.
"""

import argparse
import csv
import glob
import gzip
import os
import statistics
import sys
from collections import Counter, defaultdict

OUT = "catalog/summary"
PROV = "# generated by scripts/popseq_summarize.py from {src} on {date}"


def gz(path, mode="rt"):
    return gzip.open(path, mode, newline="") if str(path).endswith(".gz") else open(path, mode, newline="")


def load_taxmap(path):
    m = {}
    with gz(path) as fh:
        for r in csv.DictReader(fh):
            if r.get("species_taxid"):
                m[int(r["taxid"])] = (int(r["species_taxid"]), r["species_name"])
    return m


def write(name, header, rows, src, date):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    with gz(path, "wt") as fh:
        fh.write(PROV.format(src=src, date=date) + "\n")
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print(f"  {path}  {len(rows)} rows", file=sys.stderr)


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--runs", nargs="+", default=None,
                   help="ENA snapshot(s), e.g. the full snapshot plus the BGISEQ/DNBSEQ "
                        "supplement; default: the newest full snapshot in cache/")
    p.add_argument("--biosamples", default="catalog/kingdom/fungi_biosamples.csv.gz")
    p.add_argument("--taxmap", default="catalog/taxonomy_species_map.csv.gz")
    p.add_argument("--min-isolates", type=int, default=20,
                   help="species below this are pooled into an 'all others' row")
    args = p.parse_args()

    # A full snapshot is fungi_runs_ena_<YYYY-MM-DD>.tsv.gz; supplements carry a label
    # (fungi_runs_ena_bgi_<date>) and are never picked by default.
    runs_paths = args.runs or [sorted(glob.glob("cache/fungi_runs_ena_2*.tsv.gz"))[-1]]
    date = "+".join(os.path.basename(x).replace("fungi_runs_ena_", "").replace(".tsv.gz", "")
                    for x in runs_paths)
    print(f"runs: {runs_paths} (ENA snapshot {date})", file=sys.stderr)

    taxmap = load_taxmap(args.taxmap)
    print(f"taxmap: {len(taxmap)}", file=sys.stderr)

    by_year = defaultdict(lambda: [0, set()])        # (sp, year) -> runs, isolates
    studies = defaultdict(lambda: defaultdict(set))  # sp -> study -> isolates
    cov = defaultdict(list)                          # sp -> [coverage]
    name_of, sample_sp = {}, {}
    genome_mb = {}

    with gz(args.biosamples) as fh:
        pass  # opened later; keep the run pass single-threaded and cheap

    # Genome size per species. catalog/genome_sizes.csv is the fetched reference
    # table (popseq_genome_sizes.py); the species YAMLs are the older, smaller source.
    # A species with no entry gets no coverage estimate rather than a guessed one.
    if os.path.exists("catalog/genome_sizes.csv"):
        with open("catalog/genome_sizes.csv", newline="") as fh:
            for r in csv.DictReader(fh):
                if r.get("genome_mb"):
                    genome_mb[int(r["species_taxid"])] = float(r["genome_mb"])

    # Genome size per species, from the species YAMLs where they exist.
    for y in glob.glob("catalog/species/*.yaml"):
        txt = open(y).read()
        tid = mb = None
        for line in txt.splitlines():
            if line.startswith("taxid:"):
                tid = int(line.split(":", 1)[1].strip())
            if line.startswith("assumed_genome_mb:"):
                v = line.split(":", 1)[1].strip()
                mb = float(v) if v not in ("", "null") else None
        if tid and mb:
            genome_mb[tid] = mb

    def snapshot_rows():
        seen = set()
        for path in runs_paths:
            with gz(path) as fh:
                for r in csv.DictReader(fh, delimiter="\t"):
                    if r.get("run_accession") in seen:
                        continue
                    seen.add(r.get("run_accession"))
                    yield r

    for r in snapshot_rows():
        try:
            t = int(r["tax_id"])
        except (KeyError, ValueError):
            continue
        e = taxmap.get(t)
        if not e:
            continue
        sp, nm = e
        name_of[sp] = nm
        samples = [a.strip() for a in (r.get("sample_accession") or "").split(";") if a.strip()]
        for a in samples:
            sample_sp[a] = sp
        yr = (r.get("first_public") or "")[:4]
        if yr.isdigit():
            k = (sp, yr)
            by_year[k][0] += 1
            by_year[k][1].update(samples)
        stu = r.get("study_accession") or ""
        if stu:
            studies[sp][stu].update(samples)
        mb = genome_mb.get(sp)
        if mb:
            try:
                cov[sp].append(int(r.get("base_count") or 0) / (mb * 1e6))
            except ValueError:
                pass

    print("joining BioSample attributes...", file=sys.stderr)
    geo = defaultdict(Counter)
    host = defaultdict(Counter)
    source = defaultdict(Counter)
    with gz(args.biosamples) as fh:
        rd = csv.DictReader(fh)
        for row in rd:
            sp = sample_sp.get(row.get("biosample", ""))
            if not sp:
                continue
            g = (row.get("geo_loc_name") or "").split(":")[0].strip()
            if g:
                geo[sp][g] += 1
            h = (row.get("host") or "").strip()
            if h:
                host[sp][h] += 1
            s = (row.get("isolation_source") or "").strip()
            if s:
                source[sp][s] += 1

    print("writing tables:", file=sys.stderr)
    src = " + ".join(os.path.basename(x) for x in runs_paths)

    write("by_year.csv.gz", ["species_taxid", "species_name", "year", "runs", "isolates"],
          sorted(([sp, name_of[sp], yr, v[0], len(v[1])]
                  for (sp, yr), v in by_year.items()), key=lambda x: (x[1], x[2])),
          src, date)

    cl = []
    for sp, st in studies.items():
        iso = {a for s in st.values() for a in s}
        if not iso:
            continue
        per = [len(v) for v in st.values()]
        cl.append([sp, name_of[sp], len(st), len(iso),
                   round(len(iso) / len(st), 2), max(per)])
    write("clonality.csv.gz",
          ["species_taxid", "species_name", "studies", "isolates",
           "isolates_per_study", "largest_study"],
          sorted(cl, key=lambda x: -x[3]), src, date)

    gr = []
    for sp, c in geo.items():
        for country, n in c.most_common():
            gr.append([sp, name_of[sp], country, n])
    write("geography.csv.gz", ["species_taxid", "species_name", "country", "isolates"],
          sorted(gr, key=lambda x: (x[1], -x[3])), src, date)

    cr = []
    for sp, vals in cov.items():
        v = sorted(x for x in vals if x > 0)
        if not v:
            continue
        cr.append([sp, name_of[sp], len(v), round(statistics.median(v), 1),
                   round(v[len(v) // 10], 1), round(v[min(len(v) - 1, 9 * len(v) // 10)], 1),
                   sum(1 for x in v if x >= 15), sum(1 for x in v if x >= 30)])
    write("coverage.csv.gz",
          ["species_taxid", "species_name", "runs_with_estimate", "median_cov",
           "p10_cov", "p90_cov", "runs_ge_15x", "runs_ge_30x"],
          sorted(cr, key=lambda x: -x[2]), src, date)

    hs = []
    for sp in set(host) | set(source):
        for kind, c in (("host", host.get(sp, Counter())),
                        ("isolation_source", source.get(sp, Counter()))):
            for val, n in c.most_common(12):
                hs.append([sp, name_of[sp], kind, val, n])
    write("host_source.csv.gz",
          ["species_taxid", "species_name", "field", "value", "isolates"],
          sorted(hs, key=lambda x: (x[1], x[2], -x[4])), src, date)
    return 0


if __name__ == "__main__":
    sys.exit(main())
